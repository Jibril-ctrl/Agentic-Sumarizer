from langchain.tools import tool

SIGNATURE = "— Generated by Agentic Summarizer prototype — Jibril Anifowoshe"

@tool
def save_note(filename: str, content: str) -> str:
    """
    Save content to a Markdown (.md) file (append '.md' if missing).
    Appends a signature footer (credit).
    """
    try:
        if not filename.endswith(".md"):
            filename += ".md"
        footer = f"\n\n---\n{SIGNATURE}"
        with open(filename, "w", encoding="utf-8") as f:
            f.write(content + footer)
        return f"Saved notes to {filename}"
    except Exception as e:
        return f"[save_note error] {e}"

def ensure_reportlab() -> bool:
    """Try to import or pip-install reportlab inside the running kernel."""
    try:
        import reportlab  # noqa: F401
        return True
    except Exception:
        import sys, subprocess
        try:
            subprocess.check_call([sys.executable, "-m", "pip", "install", "reportlab"])
            import reportlab  # noqa: F401
            return True
        except Exception:
            return False

def save_pdf(path: str, content_text: str) -> str:
    """Write a simple text PDF with the signature footer."""
    from reportlab.lib.pagesizes import LETTER
    from reportlab.pdfgen import canvas
    from reportlab.lib.units import inch
    c = canvas.Canvas(path, pagesize=LETTER)
    width, height = LETTER
    x, y = 1*inch, height - 1*inch
    c.setFont("Helvetica", 11)
    for line in content_text.splitlines():
        while len(line) > 100:
            c.drawString(x, y, line[:100]); line = line[100:]
            y -= 0.22*inch
            if y < 1*inch:
                c.showPage(); y = height - 1*inch; c.setFont("Helvetica", 11)
        c.drawString(x, y, line)
        y -= 0.22*inch
        if y < 1*inch:
            c.showPage(); y = height - 1*inch; c.setFont("Helvetica", 11)
    c.setFont("Helvetica-Oblique", 9)
    if y < 1.2*inch:
        c.showPage(); y = height - 1*inch; c.setFont("Helvetica-Oblique", 9)
    c.drawString(x, y, SIGNATURE)
    c.save()
    return f"Saved PDF to {path}"
